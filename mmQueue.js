// ============================================================================
// Механик машин — общая очередь фоновых ИИ-операций.
//
// Дневник души (🧠) и Режиссёр (🎬) оба ходят в модель через generateRaw и делят
// один коннекшн/модель. Если запустить их одновременно — гонка и мусорные ответы.
// Поэтому обе операции проходят через ОДИН последовательный шлюз: кто встал в
// очередь — ждёт предыдущего. Не важно, кто первый — очередь сама разрулит.
//
// Использование:
//   import { mmEnqueue, mmBusy } from "./mmQueue.js";
//   await mmEnqueue(() => доСвоейРаботы());   // выполнится, когда дойдёт черёд
//   if (mmBusy()) показатьИндикатор("в очереди…");
// ============================================================================

let tail = Promise.resolve(); // хвост цепочки задач
let running = 0;              // сколько задач сейчас реально выполняется (0 или 1)

// true, если прямо сейчас что-то крутится в очереди (для индикатора «в очереди…»)
export function mmBusy() { return running > 0; }

// поставить async-операцию в очередь; промис резолвится её результатом, когда дойдёт черёд
export function mmEnqueue(fn) {
    const run = tail.then(async () => {
        running++;
        try { return await fn(); }
        finally { running--; }
    });
    tail = run.catch(() => {}); // ошибка одной задачи не рвёт очередь
    return run;
}
